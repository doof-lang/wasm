#!/bin/sh
# Regenerates tests/fixtures.do from the .wat sources in this directory.
# Requires wasm-tools (https://github.com/bytecodealliance/wasm-tools).
set -eu
cd "$(dirname "$0")"
out=../fixtures.do
{
  echo "// Generated by tests/wat/generate.sh from tests/wat/*.wat; do not edit."
  for source in *.wat; do
    name=$(basename "$source" .wat | tr 'a-z-' 'A-Z_')_MODULE
    echo
    echo "export readonly $name: readonly byte[] = ["
    wasm-tools parse "$source" | od -An -v -tu1 | awk 'NF > 0 {
      line = "  "
      for (i = 1; i <= NF; i++) line = line $i ", "
      sub(/ $/, "", line)
      print line
    }'
    echo "]"
  done
} > "$out"
